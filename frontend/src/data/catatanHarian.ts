/**
 * Mengambil catatan harian berdasarkan minggu dan hari.
 * Jika minggu > 42, akan menggunakan data minggu 42.
 * Hari berkisar antara 1-7.
 */
export const getDailyNote = (week: number, day: number): CatatanKehamilan => {
  // Batasi minggu maksimal 42
  const targetWeek = week >= 42 ? 42 : (week <= 1 ? 1 : week);
  // Batasi hari 1-7
  const targetDay = day >= 7 ? 7 : (day <= 1 ? 1 : day);

  // Cari yang pas
  const note = catatanHarian.find(n => n.minggu === targetWeek && n.hari === targetDay);
  if (note) return note;

  // Fallback 1: Cari hari pertama di minggu tersebut
  const fallbackDay1 = catatanHarian.find(n => n.minggu === targetWeek && n.hari === 1);
  if (fallbackDay1) return fallbackDay1;

  // Fallback 2: Catatan default umum
  return {
    fase: "Perkembangan Kehamilan",
    minggu: week,
    hari: day,
    tipe: "Support",
    teks: "Jaga kesehatan Bunda dan si kecil dengan tetap aktif bergerak, cukup istirahat, serta mengonsumsi nutrisi bergizi seimbang."
  };
};

/**
 * Menghitung usia kehamilan (minggu & hari) secara dinamis dari baseline minggu
 * dan tanggal kapan usia kehamilan tersebut diset.
 */
export const calculateGestationalAge = (baseWeeks: number, baseDays: number, updatedAtStr?: string | null): { weeks: number, days: number } => {
  if (!updatedAtStr) {
    return { weeks: baseWeeks, days: baseDays };
  }

  try {
    const updatedAt = new Date(updatedAtStr);
    const today = new Date();
    
    // Hitung selisih hari
    const diffTime = today.getTime() - updatedAt.getTime();
    const diffDays = Math.max(0, Math.floor(diffTime / (1000 * 60 * 60 * 24)));
    
    const totalDays = (baseWeeks * 7) + baseDays + diffDays;
    const weeks = Math.floor(totalDays / 7);
    const days = totalDays % 7; // 0 sampai 6 hari
    
    return { weeks, days };
  } catch (error) {
    console.error("Gagal menghitung usia kehamilan dinamis:", error);
    return { weeks: baseWeeks, days: baseDays };
  }
};
