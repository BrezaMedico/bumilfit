/**
 * Mengambil data perkembangan janin berdasarkan minggu kehamilan.
 * Jika minggu di luar rentang, akan dikembalikan data fallback minggu 40 atau 1.
 * 
 * @param weekNumber Angka minggu kehamilan pengguna (1 - 42)
 */
export const getFetalGrowthByWeek = (weekNumber: number): FetalGrowth => {
  const targetWeek = Math.max(1, Math.min(42, weekNumber));
  const found = fetalGrowthData.find(item => item.week === targetWeek);
  
  // Fallback pengaman jika tidak ditemukan
  return found || fetalGrowthData[targetWeek - 1] || fetalGrowthData[39];
};
